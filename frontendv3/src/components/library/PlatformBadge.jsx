const PLATFORM_LABELS = {
	steam: 'Steam',
	gog: 'GOG',
	itchio: 'Itch.io',
	pirate: 'Local',
	unknown: 'Library',
};

const PlatformBadge = React.memo(({ platform, className = '' }) => {
	const platformId = normalizeLibraryPlatformId(platform);
	const label = PLATFORM_LABELS[platformId] || PLATFORM_LABELS.unknown;
	const classes = ['lib-platform-badge', `lib-platform-badge-${platformId}`];
	if (className) classes.push(className);

	return (
		<span className={classes.join(' ').trim()} title={`Owned on ${label}`} aria-label={`Owned on ${label}`}>
			<PlatformGlyph platformId={platformId} />
			<span className="lib-platform-badge-label">{label}</span>
		</span>
	);
});

export default PlatformBadge;
