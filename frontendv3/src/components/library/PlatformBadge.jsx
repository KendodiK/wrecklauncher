export function normalizeLibraryPlatformId(rawPlatform) {
	const raw = String(rawPlatform || '').trim().toLowerCase();
	if (!raw) return 'unknown';
	if (raw === 'steam') return 'steam';
	if (raw === 'gog' || raw === 'gog.com') return 'gog';
	if (raw === 'itch' || raw === 'itchio' || raw === 'itch.io') return 'itchio';
	if (raw === 'pirate') return 'pirate';
	return 'unknown';
}

